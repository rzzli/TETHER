"""Seal the already-qualified Inspect environment without importing its runtime."""
from collections import Counter
from datetime import datetime, timezone
import hashlib
import importlib.metadata as metadata
import json
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[4]
TARGET = ROOT/"data/cache/tether-inspect-env-attempt02"
EVIDENCE = Path(__file__).parent/"attempt02"


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def write(path, value):
    with Path(path).open("xb") as stream:
        stream.write(json.dumps(value, sort_keys=True, indent=2).encode()+b"\n")


def proof(path):
    raw = path.read_bytes()
    return {"path": path.relative_to(ROOT).as_posix(), "bytes": len(raw), "sha256": sha(raw)}


def main():
    started = time.monotonic()
    assert Path(sys.prefix).resolve() == (TARGET/"environment").resolve()
    old_inventory = json.loads((TARGET/"INSTALLED-FILES.json").read_bytes())
    for record in old_inventory["files"]:
        raw = (Path(sys.prefix)/record["path"]).read_bytes()
        assert sha(raw) == record["sha256"] and len(raw) == record["bytes"], "Installed content changed after qualification"
    archive = TARGET/"installed-metadata-exact"
    archive.mkdir(exist_ok=False)
    metadata_proofs = []
    for dist in sorted(metadata.distributions(), key=lambda d: d.metadata["Name"].lower()):
        name, version = dist.metadata["Name"], dist.version
        destination = archive/(name+"-"+version)
        destination.mkdir()
        for file in dist.files:
            if ".dist-info/" in str(file).replace("\\", "/") and file.name in {
                    "METADATA", "RECORD", "WHEEL", "entry_points.txt", "top_level.txt", "INSTALLER", "direct_url.json"}:
                source = Path(dist.locate_file(file))
                raw = source.read_bytes()
                (destination/file.name).write_bytes(raw)
                metadata_proofs.append({"distribution": name, "version": version, "file": file.name,
                    "path": (destination/file.name).relative_to(TARGET).as_posix(), "bytes": len(raw), "sha256": sha(raw)})
    write(TARGET/"EXACT-METADATA.json", {"files": metadata_proofs,
        "basis": "Original installed bytes; initial read_text metadata copies remain as normalized-text audit evidence"})
    files = []
    for path in sorted(Path(sys.prefix).rglob("*")):
        if path.is_file():
            assert not path.is_symlink(), "Aliased installed environment file"
            raw = path.read_bytes()
            files.append({"path": path.relative_to(Path(sys.prefix)).as_posix(), "bytes": len(raw), "sha256": sha(raw)})
    write(TARGET/"ENVIRONMENT-INVENTORY.json", {"files": files, "file_count": len(files),
        "total_bytes": sum(f["bytes"] for f in files), "python": sys.executable})
    distributions = json.loads((EVIDENCE/"DISTRIBUTIONS.json").read_bytes())
    wheels = json.loads((EVIDENCE/"WHEELS.json").read_bytes())
    smoke = json.loads((EVIDENCE/"MOCK-EVAL-03.json").read_bytes())
    check = json.loads((EVIDENCE/"06-pip-check-with-products.json").read_bytes())
    assert smoke["status"] == "pass" and check["exit_code"] == 0
    required = ["WHEELS.json", "requirements-lock.txt", "BOOTSTRAP-WHEELS.json", "PROJECT-WHEELS.json",
                "PROJECT-SOURCE-COMPARISON.json", "DISTRIBUTIONS.json", "MOCK-EVAL-03.json", "OBSERVED-API.json",
                "06-pip-check-with-products.json", "09-mock-qualification-escalated.json"]
    unverified = Counter(Path(row["path"]).suffix for row in old_inventory["unchecked_RECORD_entries"])
    result = {"schema_version": 1, "status": "pass", "python": sys.executable, "python_version": sys.version,
        "inspect_ai_version": metadata.version("inspect-ai"), "asof_version": metadata.version("asof-target-agents"),
        "tether_version": metadata.version("tether-target-agents"), "distribution_count": distributions["count"],
        "third_party_wheel_count": wheels["wheel_count"], "third_party_wheel_bytes": wheels["total_wheel_bytes"],
        "acquisition_cap_bytes": 512*1024**2, "expanded_environment_cap_bytes": 1024**3,
        "environment_file_count": len(files), "expanded_environment_bytes": sum(f["bytes"] for f in files),
        "record_verified_files": distributions["record_verified_files"],
        "record_unhashed_entries": distributions["unchecked_record_count"], "record_unhashed_suffix_counts": dict(unverified),
        "record_unhashed_interpretation": "Original RECORD lacks expected hashes for its own files and generated bytecode; all such current bytes are captured in the separate final inventory",
        "project_sources_identical": 85, "mock_samples": 2, "mock_scores": smoke["scores"],
        "mock_generation_count": 2, "real_model_calls": 0, "external_provider_calls": 0,
        "external_network_attempts_during_mock": 0, "stdlib_loopback_self_pipe_events": len(smoke["allowed_stdlib_loopback_events"]),
        "execution_caveat": "Windows asyncio requires loopback-capable execution. Sandboxed startup independently hung; approved escalation passed. Trusted audit denies external connect/DNS/sendto; this is not an OS network sandbox.",
        "pip_check": "pass", "wire_transfer_bytes": None, "provider_cost_usd": 0,
        "prior_failures": ["Acquisition attempt01 temporary-directory monitor race", "Mock01 overstrict socket audit", "Mock02 sandboxed Windows asyncio socketpair timeout"],
        "proofs": [proof(EVIDENCE/name) for name in required] + [proof(TARGET/name) for name in
                  ("INSTALLED-FILES.json", "EXACT-METADATA.json", "ENVIRONMENT-INVENTORY.json")],
        "python_executable": proof(Path(sys.executable)), "completed_at": datetime.now(timezone.utc).isoformat(),
        "finalization_seconds": time.monotonic()-started, "finalizer_sha256": sha(Path(__file__).read_bytes())}
    assert result["expanded_environment_bytes"] < 1024**3 and wheels["total_wheel_bytes"] < 512*1024**2
    write(EVIDENCE/"ENVIRONMENT-QUALIFICATION.json", result)
    print(json.dumps({"status": "pass", "distributions": result["distribution_count"], "environment_files": len(files),
                      "environment_bytes": result["expanded_environment_bytes"], "qualification_sha256": sha((EVIDENCE/"ENVIRONMENT-QUALIFICATION.json").read_bytes())}))


if __name__ == "__main__":
    main()
